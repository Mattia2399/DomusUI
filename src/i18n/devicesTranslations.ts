const catalogs: Record<AppLocale, DevicesCatalog> = { it, en, fr };

function interpolate(message: string, parameters?: Record<string, string | number>) {
  if (!parameters) return message;
  return message.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(parameters, key) ? String(parameters[key]) : match,
  );
}

export function useDevicesTranslations() {
  const { locale } = useI18n();
  return useCallback(
    (key: DevicesTranslationKey, parameters?: Record<string, string | number>) =>
      interpolate(catalogs[locale][key], parameters),
    [locale],
  );
}

export type DevicesTranslator = ReturnType<typeof useDevicesTranslations>;
export type { DevicesTranslationKey };
