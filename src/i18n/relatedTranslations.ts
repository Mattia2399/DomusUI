const WORDS: Record<string, typeof it> = { it, en, fr };

export type RelatedWordKey = keyof typeof it;
export type RelatedWords = (key: RelatedWordKey, values?: Record<string, string | number>) => string;

export function relatedWordsOf(locale: string): RelatedWords {
  const words = WORDS[locale.slice(0, 2)] ?? it;
  return (key, values) => Object.entries(values ?? {}).reduce((text, [name, value]) => text.replace(`{${name}}`, String(value)), words[key]);
}
