const catalogs: Record<AppLocale, PanelsCatalog> = { it, en, fr };

export function usePanelsTranslations() {
  const { locale } = useI18n();
  return useCallback(
    (key: PanelsTranslationKey, parameters?: Record<string, string | number>) => {
      const message = catalogs[locale][key];
      if (!parameters) return message;
      return message.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name: string) =>
        Object.prototype.hasOwnProperty.call(parameters, name) ? String(parameters[name]) : match,
      );
    },
    [locale],
  );
}

export type PanelsTranslator = ReturnType<typeof usePanelsTranslations>;
