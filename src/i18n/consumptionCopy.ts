const copyByLocale: Record<Exclude<AppLocale, 'it'>, Record<ConsumptionCopyKey, string>> = {
  en: englishCopy,
  fr: frenchCopy,
};

function interpolate(message: string, parameters?: TranslationParameters) {
  if (!parameters) return message;
  return message.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(parameters, key) ? String(parameters[key]) : match,
  );
}

export function translateConsumption(
  locale: AppLocale,
  source: ConsumptionCopyKey,
  parameters?: TranslationParameters,
) {
  const message = locale === 'it' ? source : copyByLocale[locale][source];
  return interpolate(message, parameters);
}

export function translateConsumptionLoose(
  locale: AppLocale,
  source: string,
  parameters?: TranslationParameters,
) {
  const message = locale === 'it'
    ? source
    : (copyByLocale[locale] as Record<string, string>)[source] ?? source;
  return interpolate(message, parameters);
}

export function useConsumptionCopy() {
  const { locale, formatDate, formatNumber } = useI18n();
  const c = useCallback(
    (source: ConsumptionCopyKey, parameters?: TranslationParameters) =>
      translateConsumption(locale, source, parameters),
    [locale],
  );
  const cl = useCallback(
    (source: string, parameters?: TranslationParameters) =>
      translateConsumptionLoose(locale, source, parameters),
    [locale],
  );

  return { c, cl, formatDate, formatNumber, locale };
}

