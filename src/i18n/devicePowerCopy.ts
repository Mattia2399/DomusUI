const COPY: Record<AppLocale, Record<DevicePowerCopyKey, string>> = { it, en, fr };

export type { DevicePowerCopyKey };

export function useDevicePowerCopy() {
  const { locale } = useI18n();
  return useCallback(
    (key: DevicePowerCopyKey, parameters?: TranslationParameters) => {
      const template = COPY[locale]?.[key] ?? it[key];
      if (!parameters) return template;
      return template.replace(/\{(\w+)\}/g, (match, name: string) =>
        name in parameters ? String(parameters[name]) : match,
      );
    },
    [locale],
  );
}
