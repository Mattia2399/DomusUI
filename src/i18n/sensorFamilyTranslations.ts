export function useSensorFamilyTranslations() {
  const { locale } = useI18n();
  const devices = useDevicesTranslations();
  return useCallback(
    (key: SensorFamilyTranslationKey | DevicesTranslationKey, parameters?: Record<string, string | number>) =>
      key in catalogs[locale]
        ? interpolate(catalogs[locale][key as SensorFamilyTranslationKey], parameters)
        : devices(key as DevicesTranslationKey, parameters),
    [devices, locale],
  );
}

export type SensorFamilyTranslator = ReturnType<typeof useSensorFamilyTranslations>;
export type SensorFamilyWordKey = SensorFamilyTranslationKey | DevicesTranslationKey;
