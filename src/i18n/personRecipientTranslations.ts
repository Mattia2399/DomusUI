const COPY: Record<AppLocale, Record<PersonRecipientCopyKey, string>> = { it, en, fr };

export function personRecipientCopy(locale: AppLocale) {
  const table = COPY[locale] ?? COPY.it;
  return (key: PersonRecipientCopyKey, parameters?: Record<string, string | number>) =>
    (table[key] ?? it[key]).replace(/\{([a-z]+)\}/g, (match, name: string) =>
      parameters && name in parameters ? String(parameters[name]) : match,
    );
}
