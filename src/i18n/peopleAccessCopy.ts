const COPY: Record<AppLocale, Record<PeopleAccessCopyKey, string>> = { it, en, fr };

export type { PeopleAccessCopyKey };

export function usePeopleAccessCopy() {
  const { locale } = useI18n();
  return useCallback(
    (key: PeopleAccessCopyKey, values?: Record<string, string>) => {
      const text = COPY[locale]?.[key] ?? it[key];
      return values ? text.replace(/\{(\w+)\}/g, (match, name: string) => values[name] ?? match) : text;
    },
    [locale],
  );
}
