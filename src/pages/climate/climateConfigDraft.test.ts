import { describe, expect, it } from 'vitest';
import { emptyClimateConfig } from '../../services/climateConfigClient';
import { newCircuit, newEndpoint, newGenerator, newZone, syncClimateLinks } from './climateConfigDraft';

describe('Climate editor link maintenance', () => {
  it('keeps zone, TRV, circuit and generator links reciprocal while editing and deleting', () => {
    const config = emptyClimateConfig();
    const zone = newZone();
    const valve = newEndpoint(zone.id);
    valve.kind = 'thermostatic_radiator_valve';
    valve.roles = ['radiator_trv', 'room_heater'];
    const circuit = newCircuit();
    const generator = newGenerator('boiler');
    valve.circuitId = circuit.id;
    generator.circuitIds = [circuit.id];
    config.zones.push(zone);
    config.endpoints.push(valve);
    config.circuits.push(circuit);
    config.generators.push(generator);
    syncClimateLinks(config);
    expect(zone.endpointIds).toEqual([valve.id]);
    expect(circuit.zoneIds).toEqual([zone.id]);
    expect(circuit.endpointIds).toEqual([valve.id]);
    expect(circuit.generatorIds).toEqual([generator.id]);

    config.circuits.splice(0, 1);
    syncClimateLinks(config);
    expect(valve.circuitId).toBeNull();
    expect(generator.circuitIds).toEqual([]);
    config.zones.splice(0, 1);
    syncClimateLinks(config);
    expect(config.endpoints).toEqual([]);
  });
  it('preserves fan coil links and prunes only deleted shared resources', () => {
    const config = emptyClimateConfig();
    const zone = newZone();
    const coil = newEndpoint(zone.id);
    const ac = newEndpoint(zone.id);
    const circuit = newCircuit();
    const generator = newGenerator('boiler');
    coil.kind = 'fan_coil';
    coil.circuitId = circuit.id;
    generator.circuitIds = [circuit.id];
    circuit.generatorPreferences = [{ generatorId: generator.id, role: 'preferred' }];
    config.zones.push(zone);
    config.endpoints.push(coil, ac);
    config.circuits.push(circuit);
    config.generators.push(generator);
    config.auxiliaries = [{ id: 'dehum', name: 'Shared', kind: 'dehumidifier', zoneIds: [zone.id], circuitIds: [circuit.id], entity: { primaryEntityId: 'switch.dehum', relatedControls: [] } }];
    config.equipmentGroups = [{ id: 'outdoor', name: 'Outdoor', memberEndpointIds: [coil.id, ac.id], generatorIds: [], sharedOperatingMode: true }];
    syncClimateLinks(config);
    expect(coil.circuitId).toBe(circuit.id);
    expect(circuit.endpointIds).toEqual([coil.id]);
    expect(circuit.generatorPreferences).toEqual([{ generatorId: generator.id, role: 'preferred' }]);
    config.generators = [];
    syncClimateLinks(config);
    expect(circuit.generatorPreferences).toEqual([]);
    expect(config.equipmentGroups?.[0].memberEndpointIds).toEqual([coil.id, ac.id]);
    config.zones = [];
    syncClimateLinks(config);
    expect(config.auxiliaries?.[0].zoneIds).toEqual([]);
    expect(config.auxiliaries?.[0].circuitIds).toEqual([circuit.id]);
    config.circuits = [];
    syncClimateLinks(config);
    expect(config.auxiliaries).toEqual([]);
    expect(config.equipmentGroups).toEqual([]);
  });
});
